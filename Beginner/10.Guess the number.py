def game_engine(number):
    random_number = random.randint(2, 99)

    for i in range(number):
        guess = int(input("Make a Guess between 1 and 100: "))
        if guess == random_number:
            print("Correct")
            return
        elif guess > random_number:
            number = number - 1
            print(f"Too high\nGuess again \n\nremaining guesses: {number}")

        elif guess < random_number:
            number = number - 1
            print(f"too low\nGuess again \n\nremaining guesses: {number}")

    print("Game Over")
    return

difficulty = str(input("Type the difficulty 'easy' or 'hard': ")).lower()


if difficulty == "easy":
    game_engine(10)
elif difficulty == "hard":
    game_engine(5)
else:
    print("Wrong Input")
